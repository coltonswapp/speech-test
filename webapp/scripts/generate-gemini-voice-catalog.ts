// Regenerates lib/tts/gemini-voice-catalog.generated.ts from the Gemini
// Extended Voice Library (GET /v1beta/voices). Keeps Studio's 30 prebuilt
// voices plus every ja-JP Tokyo-accent library voice.
// Run with: pnpm tts:voice-catalog   (needs GEMINI_API_KEY)

import { writeFileSync } from "node:fs";
import { GEMINI_TTS_VOICES } from "../lib/tts/gemini-voices";

type ApiVoice = {
  id: string;
  display_name: string;
  language_code: string;
  accent: string;
  persona: string;
  context: string;
  gender: string;
  pitch: string;
  description: string;
};

async function listVoices(apiKey: string): Promise<ApiVoice[]> {
  const voices: ApiVoice[] = [];
  let pageToken = "";
  do {
    const url = new URL("https://generativelanguage.googleapis.com/v1beta/voices");
    url.searchParams.set("pageSize", "1000");
    if (pageToken) url.searchParams.set("pageToken", pageToken);
    const res = await fetch(url, { headers: { "x-goog-api-key": apiKey } });
    if (!res.ok) throw new Error(`voices.list HTTP ${res.status}: ${await res.text()}`);
    const json = await res.json();
    voices.push(...(json.voices ?? []));
    pageToken = json.next_page_token ?? json.nextPageToken ?? "";
  } while (pageToken);
  return voices;
}

function entry(v: ApiVoice, source: "studio" | "library") {
  const age = /(\d+)-year-old/.exec(v.description)?.[1];
  return {
    // Studio voices keep their capitalized name (what projects store); library
    // voices use the API id, which generateContent accepts as voiceName.
    voice: source === "studio" ? v.display_name : v.id,
    displayName: v.display_name,
    source,
    languageCode: v.language_code,
    accent: v.accent,
    gender: v.gender,
    ageYears: age ? Number(age) : null,
    pitch: v.pitch,
    persona: v.persona,
    context: v.context,
    description: v.description,
  };
}

async function main() {
  const apiKey = process.env.GEMINI_API_KEY?.trim();
  if (!apiKey) throw new Error("GEMINI_API_KEY is not set");
  const all = await listVoices(apiKey);
  const studioNames = new Set<string>(GEMINI_TTS_VOICES);
  const studio = all.filter((v) => studioNames.has(v.display_name)).map((v) => entry(v, "studio"));
  const missing = [...studioNames].filter((n) => !studio.some((s) => s.voice === n));
  if (missing.length > 0) throw new Error(`Studio voices missing from the library: ${missing.join(", ")}`);
  const library = all
    .filter((v) => v.language_code === "ja-JP" && v.accent === "Tokyo Japanese")
    .sort((a, b) => a.id.localeCompare(b.id, "en", { numeric: true }))
    .map((v) => entry(v, "library"));
  studio.sort((a, b) => a.voice.localeCompare(b.voice));

  const body = `// GENERATED by scripts/generate-gemini-voice-catalog.ts from GET /v1beta/voices
// (${new Date().toISOString().slice(0, 10)}): ${studio.length} Studio prebuilt voices + ${library.length} ja-JP Tokyo-accent
// library voices. Do not edit by hand; re-run the script.

import type { GeminiVoiceCatalogEntry } from "./gemini-voice-catalog";

export const GENERATED_GEMINI_VOICE_CATALOG: GeminiVoiceCatalogEntry[] = ${JSON.stringify([...studio, ...library], null, 2)};
`;
  writeFileSync(new URL("../lib/tts/gemini-voice-catalog.generated.ts", import.meta.url), body);
  console.log(`wrote ${studio.length} studio + ${library.length} library voices`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
